function createEquipmentSheet(workbook, type) {
  const headers = deviceSheetHeaders(type)
  const sheet = workbook.addWorksheet(type, { properties: { tabColor: { argb: type === 'Switch' ? 'FFB48EAD' : 'FF81A1C1' } } })
  sheet.columns = headers.map((header) => ({ header, key: header }))
  styleSheet(sheet)
  addListValidation(sheet, 'Dashboard', ['Show', 'Hide'])
  for (const header of headers.filter((item) => / Status$/.test(item))) addListValidation(sheet, header, ['Up', 'Down', 'Disabled'])
  for (const header of headers.filter((item) => / Number$/.test(item) && /^Port /.test(item))) addWholeNumberValidation(sheet, header, 1, MAX_SWITCH_PORTS)
  if (headers.includes('Port')) addWholeNumberValidation(sheet, 'Port', 1, 65535)
  return sheet
}


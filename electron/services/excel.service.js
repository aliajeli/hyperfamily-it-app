function switchPortHeaders() {
  const headers = []
  for (let number = 1; number <= MAX_SWITCH_PORTS; number += 1) {
    headers.push(
      `Port ${number} Number`,
      `Port ${number} VLAN`,
      `Port ${number} Status`,
      `Port ${number} IP`,
      `Port ${number} Details`
    )
  }
  return headers
}

function deviceSheetHeaders(type) {
  const headers = ['Branch Code', ...DEVICE_SHEET_FIELDS[type].map(([header]) => header), 'Dashboard']
  if (type === 'Switch') headers.push(...switchPortHeaders())
  return headers
}

function clean(value) { return String(value || 'All').replace(/[^a-z0-9_-]/gi, '_') }
function matchesQuery(device, query) {
  if (!query) return true
  const needle = String(query).toLowerCase()
  const values = [
    device.name, device.hostname, device.ip, device.port, device.model, device.asset_code, device.serial_number,
    device.location, device.connection_type, device.connection_port, device.esxi_version, device.version,
    device.user, device.domain, device.checkout_number, device.brand, device.terminal_id, device.acceptance_id,
    device.branch_name, device.branch_code, device.branch_warehouse_code,
    ...(device.switch_ports || []).flatMap((port) => [port.port_number, port.vlan, port.status, port.ip, port.details])
  ]
  return values.some((value) => String(value || '').toLowerCase().includes(needle))
}
function formatSwitchPorts(ports = []) {
  return ports.map((port) => {
    const details = [`Port ${port.port_number}`, port.vlan && `VLAN ${port.vlan}`, port.status, port.ip, port.details].filter(Boolean)
    return details.join(' · ')
  }).join('; ')
}

function valueOf(cellValue) {
  if (cellValue === null || cellValue === undefined) return ''
  if (typeof cellValue === 'object') {
    if (Object.prototype.hasOwnProperty.call(cellValue, 'result')) return valueOf(cellValue.result)
    if (Object.prototype.hasOwnProperty.call(cellValue, 'text')) return String(cellValue.text).trim()
    if (Array.isArray(cellValue.richText)) return cellValue.richText.map((item) => item.text || '').join('').trim()
    if (Object.prototype.hasOwnProperty.call(cellValue, 'hyperlink')) return String(cellValue.text || cellValue.hyperlink || '').trim()
  }
  return String(cellValue).trim()
}

function isValidHost(value) {
  if (!value) return false
  if (/^(?=.{1,253}$)(?!-)(?:[A-Za-z0-9-]{1,63}\.)*[A-Za-z0-9-]{1,63}$/.test(value)) return true
  const parts = value.split('.')
  return parts.length === 4 && parts.every((part) => /^\d+$/.test(part) && Number(part) >= 0 && Number(part) <= 255)
}

function styleSheet(worksheet, widths = {}) {
  worksheet.views = [{ state: 'frozen', ySplit: 1, xSplit: Math.min(2, worksheet.columnCount) }]
  worksheet.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: worksheet.columnCount } }
  worksheet.getRow(1).height = 28
  worksheet.getRow(1).eachCell((cell) => {
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } }
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF5E81AC' } }
    cell.alignment = { vertical: 'middle', horizontal: 'center', wrapText: true }
    cell.border = { bottom: { style: 'thin', color: { argb: 'FF4C566A' } } }
  })
  worksheet.columns.forEach((column) => {
    const header = valueOf(column.header)
    column.width = widths[header] || (/Details$/.test(header) ? 24 : /Status$|Dashboard/.test(header) ? 13 : /Branch Code|Device Name|Hostname|Model|Location|Asset/.test(header) ? 20 : 16)
  })
}

function addListValidation(worksheet, header, values, lastRow = 501) {
  const headerCell = worksheet.getRow(1).values.findIndex((value) => valueOf(value).toLowerCase() === header.toLowerCase())
  if (headerCell < 1) return
  for (let row = 2; row <= lastRow; row += 1) {
    worksheet.getCell(row, headerCell).dataValidation = {
      type: 'list', allowBlank: true, formulae: [`"${values.join(',')}"`],
      showErrorMessage: true, errorTitle: 'Choose a listed value', error: `Allowed values: ${values.join(', ')}`
    }
  }
}

function addWholeNumberValidation(worksheet, header, minimum, maximum, lastRow = 501) {
  const headerCell = worksheet.getRow(1).values.findIndex((value) => valueOf(value).toLowerCase() === header.toLowerCase())
  if (headerCell < 1) return
  for (let row = 2; row <= lastRow; row += 1) {
    worksheet.getCell(row, headerCell).dataValidation = {
      type: 'whole', operator: 'between', allowBlank: true, formulae: [minimum, maximum],
      showErrorMessage: true, errorTitle: 'Invalid number', error: `Enter a whole number from ${minimum} through ${maximum}`
    }
  }
}

